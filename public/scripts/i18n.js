  const STORAGE_KEY = 'mockServer.lang';

  let current = 'zh-CN';
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'zh-CN') current = saved;
  } catch (e) { /* 隐私模式读不到就默认中文 */ }

  function getLang() { return current; }

  /** 读取「用户自己显式选过」的语言；没选过返回 ''（此时可套用部署期默认语言） */
  function getSavedLang() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      return (saved === 'en' || saved === 'zh-CN') ? saved : '';
    } catch (e) { return ''; }
  }

  function t(key, vars) {
    // 回退顺序：当前语言 → 中文 → 英文 → 键名本身（避免漏配时把 login.xxx 这种键名渲染到界面上）
    let str = (DICT[current] && DICT[current][key] != null) ? DICT[current][key]
      : (DICT['zh-CN'] && DICT['zh-CN'][key] != null) ? DICT['zh-CN'][key]
        : (DICT.en && DICT.en[key] != null) ? DICT.en[key] : key;
    if (vars) {
      str = String(str).replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
    }
    return str;
  }

  function applyI18n(root) {
    const base = root || document;
    base.querySelectorAll('[data-i18n]').forEach((node) => {
      node.textContent = t(node.getAttribute('data-i18n'));
    });
    base.querySelectorAll('[data-i18n-html]').forEach((node) => {
      node.innerHTML = t(node.getAttribute('data-i18n-html'));
    });
    base.querySelectorAll('[data-i18n-title]').forEach((node) => {
      node.setAttribute('title', t(node.getAttribute('data-i18n-title')));
    });
    base.querySelectorAll('[data-i18n-placeholder]').forEach((node) => {
      node.setAttribute('placeholder', t(node.getAttribute('data-i18n-placeholder')));
    });
    /* value：只给「预填了默认文案、且还没被用户改过」的输入框挂（如新建规则的规则名）。
     * 用户一改，drawer.js 会把该属性摘掉，所以不会覆盖用户输入。 */
    base.querySelectorAll('[data-i18n-value]').forEach((node) => {
      node.value = t(node.getAttribute('data-i18n-value'));
    });
    base.querySelectorAll('[data-i18n-aria]').forEach((node) => {
      node.setAttribute('aria-label', t(node.getAttribute('data-i18n-aria')));
    });
  }

  /**
   * 切换语言。
   * opts.persist === false 时只改当前这次会话、不写 localStorage ——
   * 供「部署期默认语言」使用：它应当在每次访问时都生效，
   * 直到用户自己手动点过语言切换（那才是一次显式选择，要记住）。
   */
  function setLang(lang, opts) {
    if (lang !== 'en' && lang !== 'zh-CN') lang = 'zh-CN';
    current = lang;
    if (!(opts && opts.persist === false)) {
      try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) { /* 忽略 */ }
    }
    document.documentElement.lang = (lang === 'en') ? 'en' : 'zh-CN';
    applyI18n();
    if (typeof global.renderAll === 'function') global.renderAll();
    // 顶栏用户条里的角色文案（部署管理员 / 普通用户）不在 data-i18n 里，是 JS 写进
    // #userMenuRole 的，applyI18n 覆盖不到。不在这里显式重渲染，切换语言后它就会
    // 停在旧语言上（中文界面里显示 "Deploy admin"）。
    if (typeof global.renderUserBar === 'function') global.renderUserBar();
    if (typeof global.updateThemeToggle === 'function') global.updateThemeToggle();
  }

  global.I18N = { getLang, getSavedLang, t, applyI18n, setLang, LANG_KEY: STORAGE_KEY };
  global.applyI18n = applyI18n;
  global.setLang = setLang;
  global.getLang = getLang;
  global.t = t;
